/** Build a fresh catalogue holding the D1 section (registration validates every entry). */
export function buildD1Catalogue(): SchemaCatalogue {
  const catalogue = createCatalogue();
  for (const entry of D1_CATALOGUE_ENTRIES) {
    catalogue.register(entry);
  }
  return catalogue;
}

/** The D1 section as a registered catalogue (built once at import). */
export const D1_CATALOGUE: SchemaCatalogue = buildD1Catalogue();

/**
 * Assemble one migration's sql from its catalogue codes,
 * byte-identical to the base runner's inline string (the shape
 * table carries the per-migration whitespace deviations).
 */
export function d1MigrationSql(version: number): string {
  const codes = D1_MIGRATION_CODES[version];
  if (!codes) {
    throw new Error(`no D1 catalogue section for migration version ${version}`);
  }
  const shape = D1_MIGRATION_SQL_SHAPES[version] ?? DEFAULT_D1_MIGRATION_SQL_SHAPE;
  const statements = codes.map((code) => D1_CATALOGUE.get(code).statement);
  return shape.prefix + statements.join(shape.separator) + shape.suffix;
}
