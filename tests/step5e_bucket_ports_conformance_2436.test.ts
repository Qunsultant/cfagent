interface Composition {
  ports: BucketFamilyPorts;
  rawGet: (bucket: string, key: string) => string | null;
}

function doComposition(): { comp: Composition; fake: LocalFakeSessionStore } {
  const fake = new LocalFakeSessionStore();
  return {
    fake,
    comp: {
      ports: createBucketPortsFromNamespace(fake.namespace as never),
      rawGet: (bucket, key) => fake.raw(bucket, key),
    },
  };
}

function memoryComposition(): Composition {
  const adapter = new InMemoryBucketFamilyAdapter();
  return {
    ports: adapter,
    rawGet: (bucket, key) => adapter.rawValue(bucket, key),
  };
}

