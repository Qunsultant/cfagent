describe.each(flagStates)("x402 replay guard — %s", (_n, flag) => {
  it("a verified payment claims its tx hash in the store; a replay is refused as already used", async () => {
    const fake = new LocalFakeSessionStore();
    const env = paymentsEnv(fake, flag);
    const service = new ETradeAgenticPaymentService(goodOrm(), env, "sess-5e");
    const challenge = service.createX402Challenge(
      "/api/premium/stock-signals",
      0.02,
    );
    const txHash = `0x5e${crypto.randomUUID().replace(/-/g, "")}`;
    const header = {
      "PAYMENT-SIGNATURE": JSON.stringify({
        payer: "0xGood",
        signature: "0xsig",
        txHash,
        nonce: challenge.nonce,
        timestamp: Date.now(),
      }),
    };

    const first = await service.verifyPayment(header, challenge);
    expect(first.valid).toBe(true);
    // The claim is in the DO store (not merely an isolate-local set).
    expect(fake.raw("payments", `x402tx:${txHash.toLowerCase()}`)).not.toBeNull();

    // A fresh service instance over the same store refuses the replay.
    const fresh = new ETradeAgenticPaymentService(goodOrm(), env, "sess-5e");
    const replay = await fresh.verifyPayment(header, challenge);
    expect(replay.valid).toBe(false);
    expect(replay.reason).toContain("already been used");
  });

  it("a claim pre-seeded in the store refuses the payment (the store, not the caller, decides)", async () => {
    const fake = new LocalFakeSessionStore();
    const env = paymentsEnv(fake, flag);
    const service = new ETradeAgenticPaymentService(goodOrm(), env, "sess-5e");
    const challenge = service.createX402Challenge(
      "/api/premium/stock-signals",
      0.02,
    );
    const txHash = `0x5e${crypto.randomUUID().replace(/-/g, "")}`;
    fake.seed("payments", `x402tx:${txHash.toLowerCase()}`, "seeded-claim");
    const header = {
      "PAYMENT-SIGNATURE": JSON.stringify({
        payer: "0xGood",
        signature: "0xsig",
        txHash,
        nonce: challenge.nonce,
        timestamp: Date.now(),
      }),
    };
    const result = await service.verifyPayment(header, challenge);
    expect(result.valid).toBe(false);
    expect(result.reason).toContain("already been used");
  });

  it("replay across the release path: a downstream failure releases the claim, and the retry succeeds", async () => {
    const fake = new LocalFakeSessionStore();
    const env = paymentsEnv(fake, flag);
    const challengeSvc = new ETradeAgenticPaymentService(
      goodOrm(),
      env,
      "sess-5e",
    );
    const challenge = challengeSvc.createX402Challenge(
      "/api/premium/stock-signals",
      0.02,
    );
    const txHash = `0x5e${crypto.randomUUID().replace(/-/g, "")}`;
    const header = {
      "PAYMENT-SIGNATURE": JSON.stringify({
        payer: "0xGood",
        signature: "0xsig",
        txHash,
        nonce: challenge.nonce,
        timestamp: Date.now(),
      }),
    };

    // An ORM whose schema was never initialised makes the receipt
    // write fail AFTER the claim — the service must release it.
    // A receipt store whose write throws: the downstream
    // failure the release path exists for. (An uninitialized
    // DatabaseORM over the mock storage does NOT throw —
    // its create tolerates the mock — so the double stubs
    // the failing write directly.)
    const brokenOrm = {
      transactions: {
        create: () => {
          throw new Error("receipt store unavailable (fixture)");
        },
      },
      events: { create: () => ({}) },
      memory: undefined,
    } as unknown as DatabaseORM;
    const broken = new ETradeAgenticPaymentService(brokenOrm, env, "sess-5e");
    const failed = await broken.verifyPayment(header, challenge);
    expect(failed.valid).toBe(false);
    expect(fake.raw("payments", `x402tx:${txHash.toLowerCase()}`)).toBeNull();

    // The same payment, retried against a healthy service, succeeds:
    // the failed attempt did not burn the hash.
    const healthy = new ETradeAgenticPaymentService(goodOrm(), env, "sess-5e");
    const retried = await healthy.verifyPayment(header, challenge);
    expect(retried.valid).toBe(true);
  });
});

/* ------------- façade dual-run: #1245 renewal claim (§9 claims) ------------- */

const RENEW_LOGIN = "renew-5e@example.com";

function etradeEnv(fake: LocalFakeSessionStore, flag?: string): Env {
  return {
    APP_ENV: "TEST",
    ET_API_KEY: "fixture-5e-consumer-key",
    ET_API_SECRET: "fixture-5e-consumer-secret",
    ET_BASE_URL: "https://apisb.etrade.com/v1",
    SESSION_STORE: fake.namespace,
    ...(flag ? { BUCKET_PORTS_ENABLED: flag } : {}),
  } as unknown as Env;
}

const tick = (ms: number) => new Promise((r) => setTimeout(r, ms));

describe.each(flagStates)("E*TRADE renewal single-flight claim — %s", (_n, flag) => {
  it("two concurrent renewals make exactly one upstream call; the lock is released after", async () => {
    const fake = new LocalFakeSessionStore();
    const env = etradeEnv(fake, flag);
    await storeAccessTokens(env, RENEW_LOGIN, fx("access"), fx("secret"));

    let releaseFetch: (() => void) | undefined;
    const fetchSpy = vi
      .spyOn(globalThis, "fetch")
      .mockImplementation(
        () =>
          new Promise<Response>((resolve) => {
            releaseFetch = () =>
              resolve(
                new Response(
                  "oauth_token=renewed-fixture&oauth_token_secret=renewed-secret-fixture",
                  { status: 200 },
                ),
              );
          }),
      );
    try {
      const first = renewETradeAccessToken(env, RENEW_LOGIN);
      // Wait until the first renewal is provably parked inside
      // the upstream call (a fixed sleep races a cold process).
      for (let i = 0; i < 400 && fetchSpy.mock.calls.length === 0; i++) {
        await tick(5);
      }
      expect(fetchSpy).toHaveBeenCalledTimes(1);
      const second = await renewETradeAccessToken(env, RENEW_LOGIN);
      // The second caller was served the already-read tokens by the
      // duplicate claim — it never reached the upstream.
      expect(second).not.toBeNull();
      expect(fetchSpy).toHaveBeenCalledTimes(1);
      releaseFetch!();
      const firstResult = await first;
      expect(firstResult).not.toBeNull();
      expect(fetchSpy).toHaveBeenCalledTimes(1);
      // The finally-release deleted the lock key.
      expect(
        fake.raw(
          "etrade",
          `etrade:renew-lock:TEST:${RENEW_LOGIN.toLowerCase()}`,
        ),
      ).toBeNull();
    } finally {
      fetchSpy.mockRestore();
    }
  });

  it("claim unavailable fails OPEN: the renewal proceeds without single-flight (#1245 rule)", async () => {
    const fake = new LocalFakeSessionStore();
    fake.failOps.add("consume");
    const env = etradeEnv(fake, flag);
    await storeAccessTokens(env, RENEW_LOGIN, fx("access"), fx("secret"));
    const fetchSpy = vi
      .spyOn(globalThis, "fetch")
      .mockResolvedValue(
        new Response(
          "oauth_token=renewed-fixture&oauth_token_secret=renewed-secret-fixture",
          { status: 200 },
        ),
      );
    try {
      const renewed = await renewETradeAccessToken(env, RENEW_LOGIN);
      expect(renewed).not.toBeNull();
      expect(fetchSpy).toHaveBeenCalled();
    } finally {
      fetchSpy.mockRestore();
    }
  });
});
