/* ----------------- wire-protocol fake (DO-shaped) ----------------- */

interface FakeRow {
  value: string;
  expiresAt: number | null;
}

class LocalFakeSessionStore {
  entries = new Map<string, FakeRow>();
  failOps = new Set<string>();

  namespace = {
    idFromName: (name: string) => name,
    get: (_id: unknown) => ({
      fetch: async (req: Request): Promise<Response> => {
        const body = (await req.json()) as {
          op: string;
          ns: string;
          key: string;
          value?: string;
          ttl?: number;
        };
        if (this.failOps.has(body.op)) {
          return Response.json({ error: "injected failure" }, { status: 500 });
        }
        const k = `${body.ns}:${body.key}`;
        const now = Date.now();
        const live = (): FakeRow | undefined => {
          const e = this.entries.get(k);
          if (!e) return undefined;
          if (e.expiresAt !== null && e.expiresAt <= now) {
            this.entries.delete(k);
            return undefined;
          }
          return e;
        };
        switch (body.op) {
          case "get": {
            const e = live();
            return Response.json({ value: e ? e.value : null });
          }
          case "put": {
            this.entries.set(k, {
              value: body.value ?? "",
              expiresAt:
                typeof body.ttl === "number" ? now + body.ttl * 1000 : null,
            });
            return Response.json({ ok: true });
          }
          case "delete": {
            this.entries.delete(k);
            return Response.json({ ok: true });
          }
          case "consume": {
            if (live()) return Response.json({ consumed: false });
            this.entries.set(k, {
              value: body.value ?? "",
              expiresAt:
                typeof body.ttl === "number" ? now + body.ttl * 1000 : null,
            });
            return Response.json({ consumed: true });
          }
        }
        return Response.json({ error: "bad op" }, { status: 400 });
      },
    }),
  };

  raw(bucket: string, key: string): string | null {
    const e = this.entries.get(`${bucket}:${key}`);
    return e ? e.value : null;
  }

  seed(bucket: string, key: string, value: string): void {
    this.entries.set(`${bucket}:${key}`, { value, expiresAt: null });
  }
}

